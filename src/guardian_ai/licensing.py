"""Offline license verification - Ed25519-signed license files.

A product that claims 'local-only, nothing leaves the machine' cannot
phone home to a license server. The license is therefore a signed JSON
file:

    {"license": {"product": "ShieldAI", "licensee": "...",
                  "seats": 5, "issued": "ISO-8601",
                  "expires": "ISO-8601"|null, "features": [...]},
     "signature": "<base64 Ed25519 signature over canonical license JSON>"}

The vendor keeps the Ed25519 private key (generated once by
scripts/license_keygen.py); the product ships only the public key below.
Verification is a pure signature + date check - no network, no telemetry,
no activation. This is soft enforcement by design: the product reports
the license status truthfully rather than pretending DRM is unbreakable.
For the regulated B2B buyer (the actual customer for a tamper-evident
audit trail), unlicensed use is a compliance problem on their side.
"""
import base64
import json
from datetime import datetime, timezone
from pathlib import Path

# Vendor Ed25519 public key - embedded at build time. The matching
# private key lives in the gitignored .vendor/ dir (never committed,
# never in the shipped artifact). Generated by scripts/license_keygen.py.
PUBLIC_KEY_B64 = "xdcsyKnSFDsqYS/5RyTdoKG7QJsulbwegwV6t5S7v0U="


def _canonical(payload: dict) -> bytes:
    return json.dumps(payload, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def verify_license(path) -> dict:
    """Verify a signed license file. Returns a dict with:
    {valid, reason, licensee, seats, expires, features, product}
    - valid=False with an honest reason for any failure.
    - Never raises on malformed input - a broken license file is a
      reportable state, not a crash.
    """
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception as e:
        return {"valid": False, "reason": f"cannot read license: {e}"}
    lic = data.get("license")
    sig_b64 = data.get("signature")
    if not isinstance(lic, dict) or not sig_b64:
        return {"valid": False,
                "reason": "license file lacks 'license'/'signature' fields"}
    if not PUBLIC_KEY_B64:
        return {"valid": False,
                "reason": "no vendor public key embedded - "
                          "unsigned development build"}
    try:
        from cryptography.hazmat.primitives.asymmetric.ed25519 \
            import Ed25519PublicKey
        pub = Ed25519PublicKey.from_public_bytes(
            base64.b64decode(PUBLIC_KEY_B64))
        pub.verify(base64.b64decode(sig_b64), _canonical(lic))
    except Exception:
        return {"valid": False,
                "reason": "signature invalid - file is forged or tampered"}
    if lic.get("product") != "ShieldAI":
        return {"valid": False,
                "reason": f"license is for "
                          f"'{lic.get('product')}', not ShieldAI"}
    expires = lic.get("expires")
    if expires:
        try:
            end = datetime.fromisoformat(str(expires))
            if end.tzinfo is None:
                end = end.replace(tzinfo=timezone.utc)
            if datetime.now(timezone.utc) > end:
                return {"valid": False,
                        "reason": f"license expired {expires[:10]}",
                        "licensee": lic.get("licensee")}
        except ValueError:
            return {"valid": False,
                    "reason": f"bad expires field: {expires!r}"}
    return {"valid": True, "reason": None,
            "licensee": lic.get("licensee"),
            "seats": lic.get("seats"),
            "expires": expires,
            "features": lic.get("features", []),
            "product": lic.get("product")}


def license_status() -> dict:
    """Check the default license location (data_dir/shieldai.license).
    unlicensed is a reportable state, not an error."""
    from guardian_ai.paths import data_dir
    default = data_dir() / "shieldai.license"
    if not default.exists():
        return {"valid": False,
                "reason": "no license file "
                          f"({default.name} not found)"}
    return verify_license(default)
